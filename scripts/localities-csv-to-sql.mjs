#!/usr/bin/env node
// Turns localities.csv (id,slug,name,lat,lng,commune,county) into ONE safe SQL file for the Supabase SQL editor.
//
//   node scripts/localities-csv-to-sql.mjs supabase/data/localities.csv > supabase/data/localities_refresh.sql
//
// What the SQL does (and why your people keep their place):
//   - It never deletes or re-creates a row. Rows are matched by `slug` and UPDATED (lat, lng, commune, county), so every id stays the same.
//     profiles.locality_id, posts, places and events point at ids (on delete set null), so a delete-and-reimport would wipe everybody's place; this cannot.
//   - New villages (rows with no id in the CSV) are INSERTED and get their id from the database.
//   - A blank CSV cell never overwrites a value that is already in the database.
//   - `name` is never changed for an existing row. (Change a name by hand: update public.localities set name = '…' where slug = '…';)
//   - Before anything changes it checks that the (id, slug) pairs in the CSV still match the database; if not, it stops with a message and changes nothing.
//   - After the change it checks that nobody lost their locality, and rolls everything back if they did.
import { readFileSync } from 'node:fs';

// small CSV reader (handles quoted cells and "" escapes)
export function parseCsv(txt) {
  const rows = []; let row = [], cell = '', q = false;
  for (let i = 0; i < txt.length; i++) {
    const c = txt[i];
    if (q) { if (c === '"') { if (txt[i + 1] === '"') { cell += '"'; i++; } else q = false; } else cell += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n') { row.push(cell.replace(/\r$/, '')); rows.push(row); row = []; cell = ''; }
    else cell += c;
  }
  if (cell || row.length) { row.push(cell.replace(/\r$/, '')); rows.push(row); }
  const [head, ...body] = rows.filter((r) => r.some((x) => x.trim() !== ''));
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), (r[i] ?? '').trim()])));
}

const lit = (v) => (v === '' || v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const num = (v, what, row) => { const n = Number(v); if (!Number.isFinite(n)) throw new Error(`${what} is not a number in row ${row.slug}: "${v}"`); return String(n); };

export function build(rows) {
  const seen = new Set(); const existing = []; const all = [];
  for (const r of rows) {
    if (!r.slug || !r.name) throw new Error(`row without slug or name: ${JSON.stringify(r)}`);
    if (seen.has(r.slug)) throw new Error(`duplicate slug in the CSV: ${r.slug}`); seen.add(r.slug);
    const lat = num(r.lat, 'lat', r), lng = num(r.lng, 'lng', r);
    if (+lat < 43 || +lat > 49 || +lng < 20 || +lng > 30) throw new Error(`${r.slug} is outside Romania (${lat}, ${lng}). Fix the CSV first.`);
    if (r.id) { if (!/^\d+$/.test(r.id)) throw new Error(`bad id for ${r.slug}: ${r.id}`); existing.push(r); }
    all.push(`(${lit(r.slug)}, ${lit(r.name)}, ${lat}, ${lng}, ${lit(r.commune)}, ${lit(r.county)})`);
  }
  const pairs = existing.map((r) => `(${r.id}, ${lit(r.slug)})`).join(',\n    ');
  return `-- Localities refresh: ${rows.length} rows (${existing.length} existing keep their id, ${rows.length - existing.length} new). Generated by scripts/localities-csv-to-sql.mjs.
-- Safe to run more than once. Paste the whole file into the Supabase SQL editor and press Run.
begin;

alter table public.localities add column if not exists commune text, add column if not exists county text;

-- 1) Do the ids in the CSV still match the database? If not, stop before changing anything.
do $$
declare want int := ${existing.length}; got int;
begin
  select count(*) into got from public.localities l join (values
    ${pairs}
  ) as v(id, slug) on l.id = v.id and l.slug = v.slug;
  if got <> want then
    raise exception 'Stopped, nothing was changed: only % of % existing localities match the CSV (same id and slug). The CSV is out of date; export public.localities again and rebuild it.', got, want;
  end if;
end $$;

create temp table _before on commit drop as
  select (select count(*) from public.profiles where locality_id is not null) as profiles,
         (select count(*) from public.localities) as localities;

-- 2) Update by slug, insert what is new. Nothing is deleted; blank cells never erase what is already there; names are left alone.
insert into public.localities (slug, name, lat, lng, commune, county) values
${all.join(',\n')}
on conflict (slug) do update set
  lat = excluded.lat,
  lng = excluded.lng,
  commune = coalesce(nullif(excluded.commune, ''), public.localities.commune),
  county = coalesce(nullif(excluded.county, ''), public.localities.county);

-- 3) Nobody may lose their place, and no locality may disappear.
do $$
declare b record; a_profiles int; a_locs int;
begin
  select * into b from _before;
  select count(*) into a_profiles from public.profiles where locality_id is not null;
  select count(*) into a_locs from public.localities;
  if a_profiles <> b.profiles or a_locs < b.localities then
    raise exception 'Stopped and rolled back: profiles with a locality % -> %, localities % -> %.', b.profiles, a_profiles, b.localities, a_locs;
  end if;
  raise notice 'OK: % profiles keep their locality, localities % -> %.', a_profiles, b.localities, a_locs;
end $$;

commit;
notify pgrst, 'reload schema';
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const file = process.argv[2];
  if (!file) { console.error('usage: node scripts/localities-csv-to-sql.mjs localities.csv > out.sql'); process.exit(1); }
  process.stdout.write(build(parseCsv(readFileSync(file, 'utf8'))));
}
